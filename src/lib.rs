#![allow(clippy::zero_prefixed_literal)]
#![no_std]

cfg_if::cfg_if! {
    if #[cfg(target_arch = "aarch64")] {
        mod aarch64;
        pub use aarch64::permute_in_place;
    } else if #[cfg(any(target_arch = "x86", target_arch = "x86_64"))] {
        mod x86;
        pub use x86::permute_in_place;
    } else {
        unimplemented!();
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn it_works() {
        let mut bytes = [0u8; 48];

        crate::permute_in_place(&mut bytes);

        assert_eq!(
            bytes,
            [
                0xd7, 0xcf, 0x94, 0x11, 0xaa, 0x45, 0x81, 0x41, 0x75, 0x07, 0xb6, 0xf1, 0xf4, 0xcf,
                0x8e, 0xcd, 0x2c, 0xc5, 0x19, 0xd8, 0x8a, 0x33, 0x72, 0x61, 0x05, 0x13, 0x21, 0x4a,
                0xad, 0x1c, 0x50, 0x94, 0x00, 0x2a, 0x9e, 0x6b, 0x72, 0x6e, 0xed, 0x49, 0x51, 0x36,
                0x3b, 0x0d, 0x84, 0x23, 0x84, 0xdb,
            ]
        );

        for _ in 1..384 {
            crate::permute_in_place(&mut bytes);
        }

        assert_eq!(
            bytes,
            [
                0x9c, 0xa1, 0xad, 0x78, 0x8c, 0xd5, 0xc3, 0x39, 0x67, 0x9c, 0x7e, 0x55, 0x18, 0x57,
                0x73, 0x15, 0xc6, 0xea, 0x20, 0x17, 0xfc, 0x3a, 0x74, 0xd4, 0xb8, 0x4a, 0x78, 0xac,
                0xb9, 0xc8, 0x9b, 0x3c, 0x5e, 0x85, 0x6d, 0x02, 0xe9, 0x44, 0x7c, 0x45, 0xc4, 0x79,
                0x37, 0x8f, 0x90, 0x29, 0xa6, 0xe8,
            ]
        );
    }
}
